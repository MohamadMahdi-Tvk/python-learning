# یکی از دلایل محبوبیت زبان پایتون، بخاطر ماژولاریتی بودن آن است، بطوری که ماژول های خیلی خیلی زیادی داخل 
# اینترنت برای این زبان وجود دارد و کار ما را برای هر پروژه ای که روی آن کار میکنیم، بسیار بسیار ساده تر می کند

# import module name => با این ساختار می تونیم ماژول مورد نظر را ایمپورت کنیم

# مثلا ماژول رندوم را ایمپورت می کنیم:
import random

# استفاده از دستورات و فانکشن های درون ماژول:

# randint => یک بازه عددی میدهیم و از بین آن اعداد یک عدد رندوم انتخاب می کند
print(random.randint(1, 100))

# choice => یک لیستی از آیتم ها ایجاد میکنیم، خودش بصورت رندوم یکی از آن ها را انتخاب می کند
my_courses = ["python", "django", "html", "css", "js"]
print(random.choice(my_courses))

