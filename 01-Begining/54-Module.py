# همان ماژولی که ایجاد کردیم از آن اپلیکیشن بر میداریم و داخل پروژه جدید قرار میدهیم و به درستی کار می کند
# ماژول های مختلفی داریم، یکسری ماژول ها هستند که بصورت بیلت این، درون زبان پایتون قرار داده شده اند، مثل رندوم که برای
