# round(number, ndigits)

# برای رند کردن اعداد اعشاری استفاده می کند؛ یعنی مقدار صحیح یک عدد را برمیگرداند
number = 4.6
print(round(number))  # 5
# چون از چهارونیم بیشتر است، عدد پنج را در خروجی نمایش می دهد
# ولی اگر از چهارونیم کمتر باشد، عدد چهار را بر میگرداند:
number_2 = 4.3
print(round(number_2))  # 4
# اگر هم چهارونیم باشد، باز همان چهار را بر میگرداند:
number_3 = 4.5
print(round(number_3))  # 4

# تعیین تعداد ارقام رند شده:
number_4 = 4.56793434
print(round(number_4, 2))  # 4.57

# اگر هم تعداد ارقام رند شده را بیشتر از آن چیزی که عدد ما هست بدهیم،
# اروری نمی دهد و تا آنجایی که اعشار داشته باشد برمیگرداند:
number_5 = 5.232
print(round(number_5, 4))  # 5.232
