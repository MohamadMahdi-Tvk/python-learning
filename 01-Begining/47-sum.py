# sum

# تابع بدست آوردن مجموع اعداد؛ یعنی بهش یک کالکشنی از اعداد میدیم و خودش آن ها را باهم جمع می کند

numbers = [1, 2, 3]
print(sum(numbers))  # 6

# یک ورودی دوم هم میگیرد که یک عدد هست و اگر بدهیم، آن عدد را با مجموع اعداد لیست جمع می کند:
numbers_1 = [1, 2, 3]
print(sum(numbers_1, 10))  # 16

# یک توپل هم می توان به آن اضافه کرد:
my_tuple = (1, 2, 3)
print(sum(my_tuple, 20))  # 26
