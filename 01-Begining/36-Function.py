# ولی می توان وقتی مقداری را برای ورودی های فانکشن پاس میدهیم، دقیق مشخص کنیم که آرگومان ما
# برای کدام پارامتر هست؛ پس در فراخوانی ابتدا نام پارامتر را مشخص میکنیم سپس مقدار بهش میدیم:


def show_full_name(first_name, last_name):
    return f'{first_name} {last_name}'

