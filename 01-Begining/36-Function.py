# Default Parameters:
# زمان هایی هست که میخواهیم ورودی فانکشن ما مقدار پیش فرض داشته باشد
# و اگر ورودی ارسال نشد، با مقدار پیش فرض ادامه دستورات ما در فانکشن پیش برود
# مثال: فانکشن به توان رساندن یک عدد، در ورودی اول عدد و در ورودی دوم مقدار توان را دریافت می کنیم
# اگر در فراخوانی فانکشن، آرگومان توان وارد نشد، پیش فرض عدد 2 درنظر گرفته شود:
def exponent(num, power=2):
    return num ** power

print(exponent(2, 3))  # 2 * 2 * 2 => 8
print(exponent(3, 2))  # 3 * 3 => 9
print(exponent(2))  # 2 * 2 => 4

