# تعریف متغییر:

a = 100
b = 200
print(a)
print(b)

# --------------------------------------------------------------------------------------------------
# تغییر یک متغییر:

a = 100
b = 200
a = 360
c = b # ریختن متغییری در متغییر دیگر
print(a + b)
print(a + c)

# --------------------------------------------------------------------------------------------------
# تعریف همزمان متغییر ها:

w , z = 1000, 3000
print(w + z)

# --------------------------------------------------------------------------------------------------
# تغییر مقدار متغییر و ریختن آن درون خودش:

myNumber = 100
myNumber = myNumber + 40
print(myNumber)

