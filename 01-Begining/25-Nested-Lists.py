# Nested Lists (لیست های تودرتو)

# میتوانیم بجای آیتم های یک لیست، یک لیست دیگر قرار دهیم، لیستی درون لیست دیگر:

new_numbers = [[1, 2, 3], [4, 5, 6]]

# دسترسی به آیتم ها:
print(new_numbers[0])  # [1, 2, 3]

# دسترسی به یکی از آیتم های درونی
index_1 = new_numbers[1] # ابتدا لیست درونی رو بدست آوردیم
number_6 = index_1[2] # از آن لیست آیتمی که میخواستیم، یعنی ایندکس دوم رو بدست آوردیم
print(number_6) # 6

# اما برای بدست آوردن آیتم های درونی راه ساده تری هم هست:
number = new_numbers[1][2]
print(number) # 6

# هر مورد که درمورد لیست ها یاد گرفته ایم، برای لیست های تودرتو هم میتوانیم استفاده کنیم

# --------------------------------------------------------------------------------------------------
# بیرون کشیدن اعضای داخلی از هر لیست تودرتو با استفاده از حلقه تودرتو

# چاپ لیست های درونی لیست اصلی
for li in new_numbers:
    print(li)

# چاپ آیتم های درونی لیست های درونی
for li in new_numbers:
    for num in li:
        print(num)

# --------------------------------------------------------------------------------------------------
# List Comprehension in Nested Lists:

copy_list = [[print(l) for l in li] for li in new_numbers] # چاپ آیتم های درونی

# --------------------------------------------------------------------------------------------------
# ایجاد لیست های تودرتو با رینج:

# ایجاد لیست معمولی
generated_list = [num for num in range(1, 4)]
print(generated_list) # [1, 2, 3]

# ایجاد لیست تودرتو
generated_nested_list = [[new_num for new_num in range(1, 4)] for num in range(1, 5)]
print(generated_nested_list) # [[1, 2, 3], [1, 2, 3], [1, 2, 3], [1, 2, 3]]

# استفاده از منطق داخل دستور
generated_nested_list_2 = [['X' if new_num % 2 == 0 else 'O' for new_num in range(1, 4)] for num in range(1, 4)]
print(generated_nested_list_2) # [['O', 'X', 'O'], ['O', 'X', 'O'], ['O', 'X', 'O']]