# return:
# اگر فانکشنی طراحی میکنیم که دارای خروجی هست، می بایست در آخر دستورات، از کلمه کلیدی ریترن استفاده کنیم
# و در فراخوانی آن فانکشن، میتوان مقدار خروجی را داخل یک متغییر ریخت و از آن استفاده کرد
# پس بطور خلاصه، کار ریترن، این هست که یک مقداری را از یک فانکشن، خارج کند
# بطور مثال در فانکشن زیر، عدد 7 به توان 2 میرسد و نتیجه ی آن ریترن میشود
# از آن طرف نتیجه اش رو در متغییری به نام ریزالت ریخته ایم و در نهایت آن را پرینت کردیم:

def square_of_7():
    return 7 ** 2


result = square_of_7()
print(result)  # 49


# نکته مهم:
# داخل بدنه فانکشن و بعد از ریترن، هر کد دیگری قرار بدهیم اصلا اجرا نمی شود، چون در فانکشن
# اگر دستور به ریترن برسد، دستورات بعدی دیگر اعمال نمی شوند و از آنها رد می شود


def my_function():
    print("This is Before Return")
    return "This is Return"
    print("This is After Return") # این دستور اجرا نمی شود، چون بعد از ریترن آمده است


result = my_function()
print(result)
# This is Before Return
# This is Return

# نکته: لازم نیست حتما نتیجه را داخل متغییر بریزیم و بعد از آن نمایش بدهیم و مستقیما میتوانیم چاپ کنیم
print(my_function())

# مثال: فانکشن جمع اعداد 3 و 6؛ میتوان داخل فانکشن متغییر هم تعریف کرد
def add_numbers():
    a = 3
    b = 6
    return a + b

print(add_numbers()) # 9