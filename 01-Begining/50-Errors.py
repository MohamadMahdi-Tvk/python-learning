# Errors

# انواع ارور ها:

# syntax error:
# ارور هایی که از عدم رعایت درست سینتکس کدنویسی بوجود می آید؛ مثلا تایپ نان را مقدار بدیم:
# None = "Hello" => SyntaxError: cannot assign to None

# یا یک فانکشنی که هیچ چیزی ندارد:
# def my_func: => SyntaxError: expected '('

# یا اگر یک ریترن خالی قرار بدیم:
# return => SyntaxError: 'return' outside function

# یا اگر دوتا سمیکلامن قرار بدیم:
# test;; => SyntaxError: invalid syntax

# --------------------------------------------------------------------------------------------------
# name error:

# مثلا از متغییری که تعریف نشده، استفاده کنیم:
# print(name) => NameError: name 'name' is not defined

# --------------------------------------------------------------------------------------------------
# type error:

# مثلا یک فانکشن یا اپراتور اشتباهی را برای تایپ اشتباهی درنظر بگیریم:
# print(len(6))  TypeError: object of type 'int' has no len()

# یا یک رشته را بعلاوه یک لیست کنیم:
# "My Text" + [] => TypeError: can only concatenate str (not "list") to str

# --------------------------------------------------------------------------------------------------
# index error:

# اگر ایندکسی را بخواهیم که لیست ما به آن تعداد آیتم ندارد:
# numbers = [1, 2, 3, 4]
# print(numbers[6]) => IndexError: list index out of range

# --------------------------------------------------------------------------------------------------
# value error:

# مثلا اگر به متد اینت که کارش تبدیل مقدار به عدد هست، رشته پاس بدیم:
# print(int("Hello")) => ValueError: invalid literal for int() with base 10: 'Hello'

# ولی اگر رشته ای پاس بدیم که داخلش عدد باشد، مشکلی ندارد:
# print(int("30")) => 30

# --------------------------------------------------------------------------------------------------
# key error:

# زمانی که با دیکشنری ها کار می کنیم با این ارور مواجه می شویم؛ مثلا کلیدی را بخواهیم که در دیکشنری ما موجود نباشد:
# person = {}
# print(person["name"]) => KeyError: 'name'

# --------------------------------------------------------------------------------------------------
# attribute error:

# مثلا استفاده از اتربیوتی که برای آن مقدار وجود نداشته باشد؛ مثلا در اینجا تست برای رشته ما وجود ندارد:
# "mohammad".test => AttributeError: 'str' object has no attribute 'test'

# --------------------------------------------------------------------------------------------------
# ارورهای دیگری هم وجود دارد که میتوانیم آنها را از داکیومنت پایتون مطالعه کنیم