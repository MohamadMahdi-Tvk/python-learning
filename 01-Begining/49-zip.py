# zip(*args, **kwargs)

# با استفاده از این متد، میتوان چندین لیست پاس داد و آن ها را کنار هم در قالب لیستی از توپل یا دیکشنری خروجی دهد

numbers_1 = [1, 2, 3, 4]
numbers_2 = [5, 6, 7, 8]

result = zip(numbers_1, numbers_2)

print(result)  # <zip object at 0x000001A5B43E9880>
# 0x000001A5B43E9880 => آدرس زیپ آبجکت درون مموری

print(list(result))  # [(1, 5), (2, 6), (3, 7), (4, 8)]
# یک لیست درست کرد و آبجکت های آن بصورت توپل ایجاد شده اند، یعنی آیتم اول رو
# از لیست اول، و آیتم دوم رو از لیست دوم برمیدارد و همینطور الی آخر

# دیکشنری آن را هم میتوان نمایش داد
# این سری کلید اصلی آن از لیست اول و مقدارش از لیست دوم برداشته میشود:
print(dict(result))  # {1: 5, 2: 6, 3: 7, 4: 8}

# نکته: تعداد آیتم هایی که درون زیپ آبجکت وجود دارد به تعداد آیتم های موجود درون لیستی هست که آیتم کمتری دارد
numbers_3 = [1, 2, 3, 4]
numbers_4 = [5, 6, 7, 8, 9, 10]
result_2 = zip(numbers_3, numbers_4)
print(list(result_2))  # [(1, 5), (2, 6), (3, 7), (4, 8)]

# --------------------------------------------------------------------------------------------------
# برعکس عمل بالا را هم میتوان انجام داد؛ یعنی یک لیستی از توپل داریم و میخوایم به دو لیست جدا تقسیم کنیم:

my_list = [(1, 5), (3, 7), (6, 4), (7, 9)]

print(list(zip(*my_list)))  # [(1, 3, 6, 7), (5, 7, 4, 9)]

