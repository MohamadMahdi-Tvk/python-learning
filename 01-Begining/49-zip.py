# مثال: لیستی از دانشجویان داریم که دو تا لیست دارند، یک لیست نمرات میان ترم و یک لیست نمرات پایان ترم
# و میخوایم یک دیکشنری داشته باشیم که جلوی اسم هر دانشجو، بالاترین نمرات او در لیست ها را نمایش دهد

students = ["mohammad", "iman", "sara"]
midterm = [78, 80, 94]
final = [90, 88, 92]

# قدم اول اینه که بیایم نمرات میان ترم و نهایی را کنار یکدیگر قرار دهیم، برای این کار از لیست کامپرهنشن استفاده می کنیم:
# final_grades = [pair for pair in zip(midterm, final)]
# print(final_grades)  # [(78, 90), (80, 88), (94, 92)]
# حال با مکس میتوان فقط بیشترین نمره را چاپ کرد:
# final_grades = [max(pair) for pair in zip(midterm, final)]
# print(final_grades)  # [90, 88, 94]

# اما لیست نمیخوایم و نیاز به دیکشنری داریم:
# final_grades = {pair for pair in zip(students, midterm, final)}
# print(final_grades) # {('mohammad', 78, 90), ('sara', 94, 92), ('iman', 80, 88)}

# سینتکس نهایی بصورت زیر می شود:
final_grades = {t[0]: max(t[1], t[2]) for t in zip(students, midterm, final)}
print(final_grades)  # {'mohammad': 90, 'iman': 88, 'sara': 94}
# t[0] => برمیگردد به استیودنتس
# max(t[1], t[2]) => مقدار رو گفتیم بره داخل تی 1 و تی 2 که تی 1 میدترم و تی 2 فاینال هست؛ یعنی ماکس بین تی 1 و تی 2

# روش دیگر ایجاد این دیکشنری با استفاده از مپ:
final_grades_2 = zip(
    students,
    map(
        lambda pair: max(pair),
        zip(midterm, final)
    )
)
print(dict(final_grades_2))  # {'mohammad': 90, 'iman': 88, 'sara': 94}

# اگر بجای ماکس، بخوایم میانگین رو بگیریم:
average = zip(
    students,
    map(
        lambda pair: (pair[0] + pair[1]) / 2,
        zip(midterm, final)
    )
)
print(dict(average)) # {'mohammad': 84.0, 'iman': 84.0, 'sara': 93.0}