# تفاوت پارامتر و آرگومان چیست؟

# وقتی ورودی هایی را برای فانکشن خود تعریف می کنیم، به آن ورودی ها پارمتر می گویند؛ پس پارامتر در تعریف ورودی های فانکشن
# معرفی می شوند؛ اما وقتی داریم از فانکشن استفاده می کنیم و باید به ورودی ها مقدار اختصاص دهیم، به آن ورودی هایی
# که به فانکشن پاس میدیم، آرگومان می گویند

# --------------------------------------------------------------------------------------------------
# ترتیب آرگومان هایی که به یک فانکشن ارسال می کنیم، اهمیت دارند:

def divide(num_1, num_2):
    return num_1 / num_2

print(divide(3, 5)) # 0.6
print(divide(5, 3))  # 1.6666666666666667

# --------------------------------------------------------------------------------------------------
# مثال: فانکشنی برای جمع اعداد فرد درون یک لیست

my_numbers = [1, 2, 3, 4, 5, 6, 7]

def sum_odd_numbers(numbers):
    total = 0
    for num in numbers:
        if num % 2 != 0:
            total += num
    return total

print(sum_odd_numbers(my_numbers)) # 16

