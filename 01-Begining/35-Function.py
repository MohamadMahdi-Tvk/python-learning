# پارامتر ها در فانکشن

# فانکشنی داریم که برا جمع کردن باید دو تا مقدار در ورودی دریافت کند و مجموع آن ها را ریترن کند:
def sum(first_number, second_number):
    return first_number + second_number


# فراخوانی فانکشن و دادن مقادیر ورودی مورد نیاز آن:
print(sum(10, 4))  # 14

# --------------------------------------------------------------------------------------------------
# مثال: فانکشنی که نام و نام خانوادگی را دریافت می کند و آنها را در خروجی خود بهم می چسباند

name = "mohamadmahdi"
family = "tavakoli"


def show_full_name(first_name, last_name):
    return f'{first_name} {last_name}'


print(show_full_name(name, family))  # mohamadmahdi tavakoli

# استفاده از دیکشنری بجای تعریف خود متغییر ها؛ صرفا یک دیکشنری برای مشخصات فردی تعریف کرده ایم:
person = {
    "name": "MohamadMahdi",
    "family": "Tavakoli"
}

# استفاده از دیکشنری برای ورودی های فانکشن:
print(show_full_name(person["name"], person["family"])) # # MohamadMahdi Tavakoli

