# max

# ماکزیمم یک آیتم را از درون یک ایتربل برای ما بر میگرداند

numbers = [2, 43, 56, 12, 10, 16, 30]
print(max(numbers))  # 56

# برای حروف هم میتوان از این فانکشن استفاده کرد:
chars = ['a', 't', 'z']
print(max(chars))  # z

my_name = 'mostafa'
print(max(my_name))  # t

