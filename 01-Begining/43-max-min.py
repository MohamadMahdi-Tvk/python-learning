# min

# مینیموم یک آیتم را از درون یک ایتربل برای ما بر میگرداند
numbers_2 = [2, 43, 56, 12, 10, 16, 30]
print(min(numbers_2))  # 2

chars_2 = ['a', 't', 'z']
print(min(chars_2))  # a

my_name_2 = 'mostafa'
print(min(my_name_2))  # a

# --------------------------------------------------------------------------------------------------
# اگر بخوایم در یک لیست اسامی، آن اسمی که بیشترین و کمترین حروف را دارد را داشته باشیم چی؟

names = ['mohamamd', 'milad', 'akbar', 'sara', 'iman', 'ali']

# اگر لن هرکدام را بگیریم:
res = [len(name) for name in names]
print(res)  # [8, 5, 5, 4, 4]

# اگر همینجوری از ماکس استفاده کنیم، میگرده در لیست اونیو میاره که حرف اول کارکترش بزرگتر باشد:
print(max(names))  # sara

# برای این که اسمی که بیشترین کارکتر را دارد پیدا کنیم، باید از لامبدا استفاده کنیم:
print(max(names, key=lambda n: len(n)))  # mohammad

# برای مین:
print(min(names, key=lambda n: len(n)))  # ali
