# Lambda

# تعریف فانکشن بصورت معمولی:
def square(num):
    return num * num

# برای اینکه بتوانیم فانکشن رو در یک خط تعریف کنیم؛ نوع دیگری از تعریف کردن یک فانکشن، استفاده از فانکشن هست
# برای نوشتن یک لامبدا باید بصورت زیر پیاده سازی کنیم:
# lamda parameters: دستورات خود

# بطور مثال فانکشن به توان رساندن را با لامبدا به این شکل پیاده سازی میکنیم:

my_function = lambda num: num * num
print(my_function(6)) # 36

# اما ما از لامبدا معمولا به این شکل استفاده نمی کنیم، لامبدا یک فانکشنی هست که میتواند اسمی نداشته باشد، یعنی:
lambda num: num * num

# نکته: لامبدایی که می نویسیم، حتما حتما باید در یک خط تعریف شود، و بیشتر از یک خط نمی توان تعریف کرد

# مثال جمع دو عدد با لامبدا:
sum = lambda first, second: first + second
print(sum(4, 8)) # 12

# .__name__ : نام فانکشن را برمی گرداند
print(square.__name__) # square
print(my_function.__name__) # <lambda>
# در خروجی اسم فانکشن رو لامبدا برگرداند، به این دلیل که لامبدا هیچ اسمی ندارد، ما میتوانیم داخل یک متغییر بریزیم
# و از طریق اسم متغییر آن را فراخوانی کنیم، اما خود لامبدا اسمی ندارد، به اصطلاح آنانیموس فانکشن هم بهش میگن

# پس بطور کلی، لامبدا یکجورایی شبیه فانکشن هست، یعنی فانکشن تک خطی، استفاده آن به این
# صورت نیست که بریزیم داخل یک متغییری؛ اما کاربردهای زیادی دارد