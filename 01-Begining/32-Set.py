# Set

# ست ها شبیه مجموعه اعداد در ریاضی هستند، مثل لیست ها، شامل یکسری آیتم هایی هستند و یکسری
# قواعد خاصی هم دارند، مثلا در ست نمی توان مقادیر تکراری قرار داد، یا هیچ ترتیب خاصی برای آیتم ها وجود ندارد
# و به همین دلیل با استفاده از ایندکس آیتم ها، نمی توانیم به آنها دسترسی داشته باشیم

# یک ست را به این روش ایجاد می کنیم:
numbers = {1, 2, 3, 4}
print(numbers)  # {1, 2, 3, 4}

# تکرار در ست ها معنایی ندارد و اگر آیتم تکراری باشند، فقط یکی از آنها باقی می ماند
numbers_1 = {1, 2, 3, 4, 4, 4, 4, 4, 2, 2, 5}
print(numbers_1)  # {1, 2, 3, 4, 5}

# براساس ایندکس نمیشود به آیتم هایش دسترسی داشت و ارور می دهد:
# print(numbers_1[0])  # TypeError: 'set' object is not subscriptable

# اما می توان چک کرد آیا آیتمی درون ست وجود دارد یا خیر:
print(4 in numbers_1)  # True

# --------------------------------------------------------------------------------------------------
# دسترسی به آیتم های ست:

for item in numbers_1:
    print(item)  # چاپ اعداد یک تا پنج

# --------------------------------------------------------------------------------------------------
# ایجاد یک ست با استفاده از کلاسش:

# یک لیستی از دوره ها داریم:
courses = ["kotlin", "vuejs", "python", "ionic"]

# تبدیل لیست بالا به یک ست:
courses_set = set(courses)
print(courses_set)  # {'vuejs', 'ionic', 'kotlin', 'python'}

# تبدیل یک مجموعه به یک لیست:
print(list(numbers_1))  # [1, 2, 3, 4, 5]

# --------------------------------------------------------------------------------------------------
# متد های ست:

my_numbers = {1, 2, 3, 4}
print(my_numbers)  # {1, 2, 3, 4}

# add: افزودن یک آیتم جدید، اگر آیتمی که میخوایم اضافه کنیم درون مجموعه وجود داشته باشد، افزودن آن به ست اتفاق نمی افتد
my_numbers.add(5)
print(my_numbers)  # {1, 2, 3, 4, 5}

# remove: پاک کردن یک آیتم؛ یک مقدار بهش می دهیم تا همان را پاک کند
my_numbers.remove(2)
print(my_numbers)  # {1, 3, 4, 5}
# اگر عددی که میدهیم وجود نداشته باشد، ارور میدهد:
# my_numbers.remove(10)  # KeyError: 10
# برای اینکه به ارور نخوریم، قبل پاک کردن، با ایف چک میکنیم:
if 10 in my_numbers:
    my_numbers.remove(10)
print(my_numbers)  # {1, 3, 4, 5}

# discard: برای آنکه مثل بالا نیایم از گزاره شرطی ایف برای پاک کردن استفاده کنیم، از این متد استفاده می کنیم
my_numbers.discard(10)
print(my_numbers)  # {1, 3, 4, 5}
# در این متد دیگه اروری نمی دهد و اگر آیتم وجود داشت، حذف میکند، وجود نداشت هم اتفاقی نمی افتد

# copy: کپی گرفتن از ست
copy_numbers = my_numbers.copy()
print(copy_numbers)  # {1, 3, 4, 5}
# این کپی همان ستی نیست که از آن کپی گرفته شده، و فقط مقادیرشان همان هست
# ولی در مموری یک فضای مشترک را اشغال نکرده اند و از همدیگر جدا هستند
print(my_numbers == copy_numbers)  # True
print(my_numbers is copy_numbers)  # False

# clear: پاک کردن تمامی آیتم های درون ست
my_numbers.clear()
print(my_numbers)  # set()

# --------------------------------------------------------------------------------------------------
# عملیات اجتماع و اشتراک با استفاده از ست ها:

# دوره ای داریم برای پایتون که دانشجویانی دارد:
python_students = {"ali", "milad", "mohammad", "sara"}

# دوره ی کاتلین داریم که آن هم دانشجویانی دارد:
kotlin_students = {"mohammad", "ahmad", "reza", "ali"}

# اجتماع دو مجموعه:
print(python_students | kotlin_students)  # {'mohammad', 'milad', 'sara', 'reza', 'ali', 'ahmad'}

# اشتراک دو مجموعه:
print(python_students & kotlin_students)  # {'ali', 'mohammad'}

# --------------------------------------------------------------------------------------------------
# Set Comprehension:

new_set = {x ** 2 for x in range(10)}
print(new_set) # {0, 1, 64, 4, 36, 9, 16, 49, 81, 25}
# می بینیم که آیتم ها هیچ ترتیب خاصی در خروجی ندارند که این مورد از خواص ست ها است

# یک مثال دیگر، تمام کارکتر هایی که در یک رشته ای هست:
characters = {char for char in "Hello World!"}
print(characters) # {'e', '!', 'l', 'W', ' ', 'H', 'r', 'd', 'o'}
