# Tuple

# توپل ها هم مثل لیست ها، شامل مجموعه ای از آیتم ها هستند

tuple_numbers = (1, 2, 3, 4, 5)
print(tuple_numbers)

# تفاوت لیست و توپل:
# 1. در نوع تعریف و سینتکس متفاوت هستند؛ لیست با کروشه تعریف میشود، ولی توپل با پرانتز
# 2. آیتم های درون لیست را میتوانیم تغییر بدیم و حذف و اضافه کنیم، اما آیتم های توپل ایمیوتبل هستند
# ایمیوتبل یعنی قابل تغییر نیستند

# خیلی از مواردی که برای لیست ها یاد گرفتیم، برای توپل ها هم قابل اجرا هستند

# دسترسی به آیتم:
print(tuple_numbers[0])  # True

# موجود بودن یک آیتم:
print(2 in tuple_numbers)  # True

# اما اگر تلاش کنیم، آیتمی را تغییر بدیم به ما خطا می دهد:
# tuple_numbers[3] = 10 # TypeError: 'tuple' object does not support item assignment

# --------------------------------------------------------------------------------------------------
# چرا وقتی لیست ها را داریم، باید از توپل استفاده کنیم؟

# دلیل اول: سرعت توپل ها بسیار بیشتر از لیست ها هستش، علتش هم حجم کمتر آن ها نسبت به لیست ها هست
# دلیل دوم: عدم تغییر پذیری توپل، اینکه آیتم های توپل تغییر نمی کنند، باعث میشود اپلیکیشن ما امن تر شود
# یعنی گاها تغییر در آیتم های یک لیست، باعث ایجاد باگ می شود

# --------------------------------------------------------------------------------------------------
# روش دیگر ایجاد توپل، استفاده از کلمه کلیدی توپل است و باید لیستی از آیتم ها را به داخل پرانتز پاس بدیم:

new_tuple = tuple([1, 2, 3, 4, 5])
print(new_tuple)  # (1, 2, 3, 4, 5)

# --------------------------------------------------------------------------------------------------
# مثال: تعریف یک لوکیشن با استفاده از توپل ها

locations = {
    (30.21, 75.15): "Tehran",
    (40.33, 63, 91): "Shiraz"
}
print(locations[(30.21, 75.15)])  # Tehran
print(locations[(40.33, 63, 91)])  # Shiraz

# --------------------------------------------------------------------------------------------------
# استفاده از حلقه فور برای توپل ها هم امکانپذیر است:

for num in tuple_numbers:
    print(num)  # اعداد یک تا پنج را چاپ می کند

# --------------------------------------------------------------------------------------------------
# متد هایی که برای توپل ها میتوان استفاده کرد:

tuple_numbers_2 = (1, 2, 3, 4, 5, 3, 2, 5, 6, 3, 3)

# count: تعداد تکرار آن آیتمی که در ورودی دریافت می کند
print(tuple_numbers_2.count(3))  # 4

# index: مقدار میدهیم تا شماره ایندکس آن را برگرداند
print(tuple_numbers_2.index(1))  # 0
print(tuple_numbers_2.index(3))  # 2

# اگر داخل توپل، توپل دیگری وجود داشته باشد:
tuple_numbers_3 = (1, 2, 3, 4, 5, 2, (4, 5, 3), 3, 3)
print(tuple_numbers_3[6])  # (4, 5, 3)
# دسترسی به آیتم درونی توپل تودرتو؛ مثلا به آیتم شماره 5 میخواهیم دسترسی داشته باشیم:
print(tuple_numbers_3[6][1])  # 5

# --------------------------------------------------------------------------------------------------
# تمامی مباحثی که در اسلایسینگ لیست ها بررسی شدند، برای توپل ها هم قابل استفاده هست:

tuple_numbers_4 = (1, 2, 3, 4, 5, 2, (4, 5, 3), 3, 3)
print(tuple_numbers_4[0:2])  # (1, 2)
