# map(func, *iterables)

# گاها پیش میاد که یک فانکشن را به عنوان پارامتر ورودی، به یک فانکشن دیگر ارسال کنیم؛ در تعریف فانکشن مپ
# میبینیم که به ورودی آن یک فانکشن باید یک فانکشن پاس بدیم و یک ایتربلز؛ پس وقتی ما بخوایم یک فانکشنی
# را به ورودی فانکشن دیگری ارسال کنیم، باید از لامبدا استفاده کنیم
# iterables: چیزی هست که میتونیم روی آیتم های آن ایتریت یا پیمایش کنیم، مثل یک لیست، ست یا توپل

numbers = [1, 2, 3, 4, 5]

# میخوایم آیتم های درون لیست دو برابر شوند، میتونیم با روش های مختلفی این کار را انجام دهیم
# مثلا روش استفاده از حلقه فور:
doubles_for = []
for num in numbers:
    doubles_for.append(num * 2)

print(doubles_for)  # [2, 4, 6, 8, 10]

# روش بعدی که مرسوم تر هست، استفاده از لامبدا و مپ هست؛ که خیلی ساده تر است:
# doubles = map(lambda x: x * 2, numbers)
# ایکس که بعد از لامبدا گذاشته شده، نماینده تک تک آیتم های موجود درون ایتربیل نامبرز است
# اما اگر همینجور پرینت کنیم چنین چیزی خروجی میدهد:
# print(doubles) # <map object at 0x0000018D5D539540>
# برای اینکه خروجی رو درست نمایش دهد، مپ رو به لیست باید تبدیل کنیم:
doubles = list(map(lambda x: x * 2, numbers))
print(doubles)  # [2, 4, 6, 8, 10]

# اگر در مپ به لیست تبدیل نکرده بودیم، موقع پرینت هم میتوانیم آن را به لیست تبدیل کنیم، یعنی:
# print(list(doubles))

# --------------------------------------------------------------------------------------------------
# در مپ، فقط یکبار میشود روی آیتم ها پیمایش انجام داد

# لیست زیر را داریم:
numbers_1 = [1, 2, 3, 4, 5]

# از مپ استفاده می کنیم:
doubles_1 = map(lambda x: x * 2, numbers_1)

# چاپ مپ آبجکت:
print(doubles_1)  # <map object at 0x00000258D599A540>

# یکبار پرینت میکنیم:
print(list(doubles_1))  # [2, 4, 6, 8, 10]

# سری دومی که آن را پرینت کنیم:
print(list(doubles_1))  # []
# در سری دوم، لیست ما خالی از آیتم شد، این قابلیت مپ است، ساختار مپ به این صورت هست
# که ما میتوانیم فقط یک بار پیمایش را انجام دهیم، بار دوم آیتم ها خالی میشوند

# --------------------------------------------------------------------------------------------------
# مثال : اسامی که درون لیست هستند، با استفاده از مپ بصورت حرف بزرگ تبدیل شوند

names = ["mohammad", "sara", "iman", "ali"]

upper_names = map(lambda name: name.upper(), names)

print(list(upper_names))  # ['MOHAMMAD', 'SARA', 'IMAN', 'ALI']

# --------------------------------------------------------------------------------------------------
# مثال : لیستی از دیکشنری ها داریم و میخوایم فقط آیتم مدنظر خود را واکشی کنیم

people = [
    {'name': 'mohammad', 'family': 'ordookhani', 'age': 23},
    {'name': 'sara', 'family': 'moradi', 'age': 25},
    {'name': 'iman', 'family': 'madaeny', 'age': 30},
]

# میخوایم داخل یک لیستی، فقط نام خانوادگی افراد رو داشته باشیم:
families = map(lambda person: person['family'], people)

print(list(families))  # ['ordookhani', 'moradi', 'madaeny']

# اگر بخوایم همین مثال را با حلقه پیاده سازی کنیم، به این صورت می شود:
families_2 = []

for person in people:
    families_2.append(person['family'])

print(families_2)  # ['ordookhani', 'moradi', 'madaeny']

# با مپ، حتی میتوان در یک خط هم همین عملیات را انجام داد:
print(list(map(lambda person: person['family'], people))) # ['ordookhani', 'moradi', 'madaeny']
