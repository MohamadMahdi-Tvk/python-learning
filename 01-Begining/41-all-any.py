# all(iterable)

# این فانکشن میاد تروسینس و فالسینس رو بررسی می کند، اگر آیتم های داخل یک ایتربیل همه شون درست باشند
# ترو را ریترن می کند:
print(all([1, 2, 3, 4]))  # True

# اما اگر 1 را 0 کنیم فالس بر میگرداند؛ چون عدد 0 پیش فرض فالس درنظر گرفته می شود
print(all([0, 2, 3, 4]))  # False

# بنابراین، این فانکشن تروسینس تک تک آیتم های درونی را بررسی می کنند اگر همه آیتم های ترو باشند
# ترو را ریترن می کند، اگر نه فالس ریترن می کند؛ اگر ایتربیل خالی باشد هم ترو برمیگرداند:
print(all([]))  # True

# --------------------------------------------------------------------------------------------------
# مثال: داخل لیست چک کنیم ببینیم که همه ی آیتم های آن زوج هستند یا خیر
numbers = [2, 4, 6, 8]

print([num for num in numbers if num % 2 == 0]) # [2, 4, 6, 8]

print([num % 2 == 0 for num in numbers]) # [True, True, True, True]

print(all([num % 2 == 0 for num in numbers])) # True

# در لیست زیر یکی از اعداد را فرد قرار میدهیم
numbers_2 = [2, 4, 7, 8]
print(all([num % 2 == 0 for num in numbers_2])) # False

# پس بطور کلی در آل همه ی آیتم های درون ایتربیل باید ترو باشد، تا ترو را برگرداند

# --------------------------------------------------------------------------------------------------
# any(iterable)

# بر عکس آل، که اگر تمامی آیتم ها ترو بودند، ترو برگردانده میشد، در فانکشن انی
# اگر یک آیتم هم در ایتربیل، درست یا ترو باشد، ترو را برمیگرداند:

my_numbers = [0, 0, 0, 0]
print(any(my_numbers)) # False => [False, False, False, False]

my_numbers_1 = [0, 0, 0, 1]
print(any(my_numbers_1)) # True => [False, False, False, True]

# اگر لیست خالی باشد، فالس برمیگرداند:
print(any([])) # False

# --------------------------------------------------------------------------------------------------
# مثال: بررسی اعداد فرد در لیست

my_numbers_2 = [2, 4, 6, 7]

# ترو برمیگرداند، چون یک عدد فرد داخل لیست وجود دارد
print(any([num % 2 != 0 for num in my_numbers_2])) # True

# اگر تمامی اعداد داخل لیست زوج باشند، فالس برمیگرداند؛ چون هیچ عدد فردی داخل لیست وجود ندارد:
my_numbers_3 = [2, 4, 6, 8]

print(any([num % 2 != 0 for num in my_numbers_3])) # False